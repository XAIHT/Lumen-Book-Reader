def render_pyinstaller_version_file(
    version: str,
    *,
    product_name: str = PRODUCT_NAME,
    company_name: str = COMPANY_NAME,
    file_description: str = "Lumen Book Reader — created by Angela López Mendoza (XAIHT)",
    internal_name: str = "Lumen",
    original_filename: str = "Lumen.exe",
    legal_copyright: str = COPYRIGHT,
    author: str = AUTHOR,
) -> str:
    """Return the contents of a PyInstaller ``--version-file``.

    Windows reads ``ProductVersion`` out of this resource, which is exactly how
    ``install.py`` / ``uninstall.py`` learn their own version when frozen - so
    the GUI badge and the Explorer properties sheet are the same string by
    construction, not by convention.
    """
    filevers = semver_to_win32_tuple(version)
    public = public_version(version)
    return f"""# UTF-8
#
# Win32 VERSIONINFO resource generated by Lumen's build scripts.
# Do not edit by hand - regenerate via ``python build.py [--version X.Y.Z]``.
#
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={filevers},
    prodvers={filevers},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          u'040904B0',
          [
            StringStruct(u'CompanyName',      u'{company_name}'),
            StringStruct(u'Author',           u'{author}'),
            StringStruct(u'Creator',          u'{author}'),
            StringStruct(u'FileDescription',  u'{file_description}'),
            StringStruct(u'FileVersion',      u'{public}'),
            StringStruct(u'InternalName',     u'{internal_name}'),
            StringStruct(u'LegalCopyright',   u'{legal_copyright}'),
            StringStruct(u'OriginalFilename', u'{original_filename}'),
            StringStruct(u'ProductName',      u'{product_name}'),
            StringStruct(u'ProductVersion',   u'{version}'),
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
"""


